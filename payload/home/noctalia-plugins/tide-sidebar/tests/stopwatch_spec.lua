local base="tide-sidebar/"
local file=io.open(base.."lib/stopwatch.luau","r");if file then file:close() else base="" end
local S=dofile(base.."lib/stopwatch.luau")
local checks=0
local function check(value,name)assert(value,name);checks=checks+1 end
local idle=S.new()
check(idle.status=="idle" and S.elapsed(idle,1000)==0,"initial zero")
local running=assert(S.start(idle,1000))
check(idle.status=="idle","input state is immutable")
check(S.elapsed(running,2345)==1345,"elapsed uses absolute anchor")
local once=assert(S.lap(running,2500))
check(#running.laps==0 and once.laps[1].totalMs==1500 and once.laps[1].splitMs==1500,"lap is immutable")
local twice=assert(S.lap(once,4000))
check(twice.laps[2].index==2 and twice.laps[2].totalMs==3000 and twice.laps[2].splitMs==1500,"split duration")
local paused=assert(S.pause(twice,4500))
check(paused.elapsedMs==3500 and paused.startedAtMs==nil,"pause captures total")
check(S.elapsed(paused,80000)==3500,"paused elapsed is stable")
local resumed=assert(S.start(paused,10000))
check(S.elapsed(resumed,11050)==4550,"resume preserves accumulated time")
local snap=assert(S.snapshot(resumed,12000))
check(snap.elapsedMs==5500 and snap.startedAtMs==12000,"snapshot rebases safely")
local restored=assert(S.restore(snap,22000))
check(S.elapsed(restored,23000)==16500,"closed/restarted shell time retained")
local pausedRestored=assert(S.restore(paused,23000))
check(S.elapsed(pausedRestored,99999)==3500,"paused restart stays paused")
local reset=assert(S.reset(resumed,24000))
check(reset.status=="idle" and #reset.laps==0 and reset.elapsedMs==0,"reset only its own stopwatch")
check(not S.lap(idle,1000),"lap requires running")
check(S.format(65432)=="01:05.43","hundredth display")
check(S.format(3600123)=="01:00:00.12","hour display")
check(S.elapsed(running,500)==0,"clock rollback never negative")
check(S.elapsed(twice,500)>=3000,"clock rollback never below recorded lap")
check(not S.start(idle,0/0),"invalid clock rejected")
check(not S.restore({version=1,status="running",elapsedMs=0,laps={}},1000),"missing anchor rejected")
check(not S.restore({version=1,status="idle",elapsedMs=1,laps={}},1000),"invalid idle rejected")
check(not S.restore({version=1,status="paused",elapsedMs=20,laps={{index=1,totalMs=20,splitMs=19}}},1000),"invalid split rejected")
local many=assert(S.start(S.new(),0))
for i=1,100 do many=assert(S.lap(many,i*1000)) end
check(#many.laps==100 and not S.lap(many,101000),"lap cap keeps original records")
print("stopwatch_spec: "..checks.." checks passed")
